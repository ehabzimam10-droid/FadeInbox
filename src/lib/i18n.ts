export function changeLanguage(langCode: LanguageCode) {
  i18n.changeLanguage(langCode);
  localStorage.setItem('fadeinbox_lang', langCode);

  const selectedLang = LANGUAGES.find((l) => l.code === langCode);
  const dir = selectedLang?.dir || 'ltr';

  document.documentElement.setAttribute('dir', dir);
  document.documentElement.setAttribute('lang', langCode);
}

// Initial setup on module load
const initialLang = (localStorage.getItem('fadeinbox_lang') as LanguageCode) || 'en';
changeLanguage(initialLang);

